import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const fullCatalog=JSON.parse(read('data/catalog.json'));
const originalV7=new Set(JSON.parse(read('data/v7-resource-ids.json')));
const cat={...fullCatalog,resources:fullCatalog.resources.filter(r=>originalV7.has(r.id))};
const lessons=cat.resources.filter(r=>r.type==='lesson');
assert.equal(lessons.length,30);
let additions=0,groupsCount=0,markedTerms=0;
const fingerprintInputs=[];
for(const r of cat.resources){
 const d=JSON.parse(read(r.file));
 for(const q of r.type==='lesson'?d.practice:d.questions){
   fingerprintInputs.push({resource:r.id,id:q.id,prompt:q.prompt,choices:q.choices,answer:q.answer,translationId:q.translationId??null});
 }
 if(r.type!=='lesson')continue;
 const groups=d.blocks.filter(b=>b.type==='example_group');
 assert.deepEqual(groups.map(g=>g.items.length),[3,3,2],`${r.id}: missing guided examples`);
 assert.deepEqual(groups.map(g=>g.collapsed),[false,false,true],`${r.id}: progressive disclosure broken`);
 assert.ok(groups.every(g=>g.items.every(x=>x.english.trim()&&x.indonesian.trim()&&x.note.trim())),`${r.id}: incomplete example translation/note`);
 assert.ok(groups.every(g=>g.items.every(x=>!x.english.includes('[['))),`${r.id}: English example has Indonesian markup`);
 const vocab=d.blocks.filter(b=>b.type==='vocabulary');
 assert.equal(vocab.length,1,`${r.id}: missing vocabulary`);
 assert.equal(vocab[0].items.length,4,`${r.id}: 4 vocabulary definitions required`);
 assert.ok(vocab[0].items.every(x=>x.english&&x.indonesian));
 const breakdown=d.blocks.filter(b=>b.type==='breakdown');
 assert.equal(breakdown.length,1,`${r.id}: missing sentence breakdown`);
 assert.ok(breakdown[0].parts.length>=2&&breakdown[0].parts.every(x=>x.english&&x.meaning));
 assert.equal(breakdown[0].sentence,groups[0].items[0].english,`${r.id}: breakdown differs from example`);
 const summary=d.blocks.filter(b=>b.type==='summary');
 assert.equal(summary.length,1,`${r.id}: missing recap`);
 assert.equal(summary[0].items.length,3,`${r.id}: recap needs 3 reminders`);
 assert.ok(r.estimatedMinutes>=15,`${r.id}: learning time not refreshed`);
 const prose=[...d.objectives,...d.blocks.flatMap(b=>[b.text,b.note,b.explanation,...(b.items||[]).flatMap(x=>x.note??(typeof x==='string'?x:'')),...(b.parts||[]).map(x=>x.meaning)].filter(x=>typeof x==='string')),...d.practice.map(q=>q.explanation)];
 const tokens=prose.flatMap(p=>[...p.matchAll(/\[\[([^\[\]]+)\]\]/g)]);
 markedTerms+=tokens.length;
 assert.ok(tokens.length>=5,`${r.id}: insufficient English term highlighting`);
 assert.ok(prose.every(p=>p.match(/\[\[/g)?.length===p.match(/\]\]/g)?.length || (!p.includes('[[')&&!p.includes(']]'))),`${r.id}: malformed inline markup`);
 additions+=groups.reduce((n,g)=>n+g.items.length,0);groupsCount+=groups.length;
}
assert.equal(additions,240);assert.equal(groupsCount,90);
assert.ok(markedTerms>=300);
assert.equal(fingerprintInputs.length,234);
const fingerprint=crypto.createHash('sha256').update(JSON.stringify(fingerprintInputs)).digest('hex');
assert.equal(fingerprint,'1ab63451338726dd62859906adf15bb0cdb41ca8dfe58f816f4c935961219c94','V5 questions or English answer positions changed');
assert.match(read('js/lesson.js'),/formatIdText\(q.explanation\)/,'Practice feedback must render safe highlighted terms');
assert.match(read('css/style.css'),/\.english-term/);
const core=read('js/core.js');
const excerpt=core.slice(core.indexOf('// V6: explicit'));
const esc=`const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));\n`;
const {formatIdText,blocks}=await import('data:text/javascript;base64,'+Buffer.from(esc+excerpt).toString('base64'));
assert.equal(formatIdText('Pakai [[verb]] yang tepat.'),'Pakai <span class="english-term" lang="en">verb</span> yang tepat.');
const escaped=formatIdText('Baca [[<img src=x onerror=alert(1)>]] & lanjut');
assert.ok(escaped.includes('&lt;img')&&escaped.includes('&amp;')&&!escaped.includes('<img'));
const rendered=blocks([{type:'example_group',title:'Contoh',collapsed:true,items:[{english:'She reads.',indonesian:'Dia membaca.',note:'[[She]] diikuti verb.'},{english:'He reads.',indonesian:'Dia membaca.',note:'Juga benar.'}]},{type:'summary',title:'Ringkasan',items:['[[verb]] benar','Pelajari ulang']}]);
assert.match(rendered,/<details/);assert.match(rendered,/<summary/);assert.match(rendered,/lang="en"/);assert.match(rendered,/Dia membaca/);assert.match(rendered,/<aside/);
console.log(`PASS V6: ${lessons.length} expanded lessons, ${additions} new explained examples, ${groupsCount} progressive groups, vocab/breakdown/recap, ${markedTerms} inline English labels; all 234 V5 questions unchanged; renderer escapes HTML.`);
