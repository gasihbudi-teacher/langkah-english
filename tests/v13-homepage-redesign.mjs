import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html');
const home=read('js/home.js');
assert.match(html,/class="dashboard-welcome"/);
assert.match(html,/id="learning-choices"/);
assert.match(html,/id="continue-section"[^>]*hidden/);
assert.match(html,/id="my-progress"/);
assert.match(html,/<nav id="learning-choices"[^>]*data-i18n-aria="pathNav"/);
const destinations = ['grammar.html#beginner', 'school.html', 'utbk.html', 'tka.html', 'sas.html', 'text-based.html'];
const wheel = html.match(/<svg class="learning-wheel"[^>]*>([\s\S]*?)<\/svg>/)?.[1];
assert.ok(wheel, 'Missing learning wheel');
assert.deepEqual([...wheel.matchAll(/<a href="([^"]+)"/g)].map(match => match[1]), destinations);
for(const removed of ['class="path-list"','id="choices-title"','class="pathway-shortcut"','data-i18n="progressHistory"','id="pathways"','id="journey-title"','id="grades-title"','id="roadmap-title"'])assert.ok(!html.includes(removed),`Redundant homepage section remains: ${removed}`);
for(const id of ['stats','activity','backup-export','backup-import','backup-status'])assert.match(html,new RegExp(`id="${id}"`),`Progress/backup feature missing: ${id}`);
assert.match(home,/continueSection\.hidden=!hasProgress/,'Returning-user continuation should not appear for a brand-new learner.');
assert.match(home,/setupBackup\(renderHome\)/,'Backup restore must refresh the progress panel.');
const source=read('js/i18n.js')+'\nexport {dictionary};';
const {dictionary}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual(Object.keys(dictionary.en).sort(),Object.keys(dictionary.id).sort(),'English and Indonesian interface keys must stay in sync.');
for(const key of ['heroOverline','heroTitle','choiceTitle','choiceOne','choiceTwo','choiceThree','choiceFour','navSas','sasIntro','homeSearchHint','homeSearchLink','progressTitle','weekActivity','weekDone','weekNone','progressHistory'])assert.ok(dictionary.en[key]&&dictionary.id[key],`Missing homepage translation: ${key}`);
console.log('PASS homepage redesign: one clear hero, six wheel links, continuation only for returning learners, backup preserved, bilingual keys in sync.');
