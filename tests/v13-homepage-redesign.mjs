import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html');
const home=read('js/home.js');
assert.match(html,/class="hero home-hero"/);
assert.match(html,/id="learning-choices"/);
assert.match(html,/id="continue-section"[^>]*hidden/);
assert.match(html,/<details class="section home-progress-details" id="my-progress">/);
for(const href of ['grammar.html#beginner','school.html','utbk.html','tka.html'])assert.match(html,new RegExp(`class="choice-card" href="${href.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}"`));
for(const removed of ['id="pathways"','id="journey-title"','id="grades-title"','id="roadmap-title"'])assert.ok(!html.includes(removed),`Redundant homepage section remains: ${removed}`);
for(const id of ['stats','activity','backup-export','backup-import','backup-status'])assert.match(html,new RegExp(`id="${id}"`),`Progress/backup feature missing: ${id}`);
assert.match(home,/continueSection\.hidden=!hasProgress/,'Returning-user continuation should not appear for a brand-new learner.');
assert.match(home,/setupBackup\(renderHome\)/,'Backup restore must refresh the progress panel.');
const source=read('js/i18n.js')+'\nexport {dictionary};';
const {dictionary}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual(Object.keys(dictionary.en).sort(),Object.keys(dictionary.id).sort(),'English and Indonesian interface keys must stay in sync.');
for(const key of ['heroOverline','heroTitle','heroBody','heroPrimary','choiceTitle','choiceOne','choiceTwo','choiceThree','choiceFour','homeSearchHint','homeSearchLink','progressTitle'])assert.ok(dictionary.en[key]&&dictionary.id[key],`Missing homepage translation: ${key}`);
console.log('PASS homepage redesign: one clear hero, four distinct routes, optional progress details, continuation only for returning learners, backup preserved, bilingual keys in sync.');
