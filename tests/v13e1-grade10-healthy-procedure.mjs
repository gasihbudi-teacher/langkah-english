import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {validateQuestion,score,isCorrect,isAnswered} from '../js/question-types.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const load=p=>JSON.parse(read(p));
const catalog=load('data/catalog.json');
const lessonMeta=catalog.resources.find(r=>r.id==='grade10-healthy-procedure');
const quizMeta=catalog.resources.find(r=>r.id==='grade10-healthy-procedure-practice');
assert(lessonMeta&&quizMeta,'Grade 10 healthy procedure lesson and transfer assessment must remain registered');
assert.deepEqual(lessonMeta.placements,[{pathway:'school',grade:10}]);
assert.deepEqual(quizMeta.placements,[{pathway:'school',grade:10}]);
assert.deepEqual(lessonMeta.relatedLessons.slice(0,1),['grade10-healthy-procedure-practice']);
assert.deepEqual(quizMeta.relatedLessons,['grade10-healthy-procedure']);
assert.deepEqual(lessonMeta.prerequisites,['grade9-upcycling-procedure']);
const lesson=load(lessonMeta.file);
assert.equal(lesson.id,'grade10-healthy-procedure');
assert.deepEqual(lesson.assessments,['grade10-healthy-procedure-practice']);
assert.equal(lesson.blocks[0].type,'definition');
assert.equal(lesson.blocks[1].type,'scaffold');
assert.equal(lesson.blocks[2].type,'synthesis');
assert.equal(lesson.blocks.at(-1).type,'vocabulary');
const scaffold=lesson.blocks[1];
assert(scaffold.modelEnglish&&scaffold.modelIndonesian&&scaffold.modelNote);
assert.equal(scaffold.modelPosition,'after');
const words=scaffold.modelEnglish.trim().split(/\s+/).length;
assert(words>=200&&words<=280,`Connected model length: ${words}`);
assert.equal(scaffold.modelEnglish.split(/\n\s*\n/).length,4,'English model must have four connected paragraphs');
assert.equal(scaffold.modelIndonesian.split(/\n\s*\n/).length,4,'Indonesian model must preserve four paragraph breaks');
assert.match(read('css/style.css'),/\.lesson-translation\s*\{\s*white-space:\s*pre-line\s*;?\s*\}/,'Indonesian translation CSS must preserve paragraph breaks');
assert.equal(scaffold.steps.length,8);
assert(scaffold.steps.every(s=>s.phase&&s.title&&s.explanation&&s.english&&s.indonesian&&s.why));
assert(scaffold.steps.every(s=>(!!s.check)===(!!s.checkAnswer)));
assert.equal(scaffold.steps.filter(s=>s.check).length,3);
assert(scaffold.steps.some(s=>/tujuan dan siapa/i.test(s.title)));
assert(scaffold.steps.some(s=>/kata kerja imperatif/i.test(s.title)));
assert(scaffold.steps.some(s=>/kewajiban, anjuran/i.test(s.title)));
assert(scaffold.steps.some(s=>/kondisi yang mengubah/i.test(s.title)));
assert(lesson.blocks.some(b=>b.type==='table'&&b.headers.includes('Penanda dalam teks')));
assert(lesson.blocks.some(b=>b.type==='mistake'&&b.incorrect.includes('should to')));
assert.equal(lesson.blocks.filter(b=>b.type==='example_group').length,3);
assert.equal(lesson.blocks.filter(b=>b.type==='example_group').reduce((n,b)=>n+b.items.length,0),10);
assert.equal(lesson.blocks.filter(b=>b.type==='checkpoint').length,1);
assert.equal(lesson.blocks.filter(b=>b.type==='reflection').length,1);
assert.equal(lesson.blocks.filter(b=>b.type==='self_check').length,1);
assert.equal(lesson.practice.length,2);
for(const q of lesson.practice){assert(q.translationId?.prompt);assert.equal(q.translationId.choices.length,q.choices.length);assert(q.explanation.length>45);}
assert.match(scaffold.modelEnglish,/allergies and dietary needs/i);
assert.match(scaffold.modelEnglish,/If you cannot keep it cold/i);
assert.match(scaffold.modelEnglish,/Do not pack food beyond its expiry date/i);
assert.match(scaffold.modelIndonesian,/\n\n/);
const quiz=load(quizMeta.file);
assert.equal(quiz.id,'grade10-healthy-procedure-practice');
assert.equal(quiz.questionCount,7);
assert.equal(quiz.questions.length,7);
assert.equal(quiz.durationSeconds,480);
assert.equal(quiz.passages.length,1);
assert(quiz.passages[0].text.trim().split(/\s+/).length>=130);
assert.equal(quiz.passages[0].original,true);
assert.equal(new Set(quiz.questions.map(q=>q.id)).size,7);
for(const q of quiz.questions){
 assert.doesNotThrow(()=>validateQuestion(q),q.id);
 assert.equal(q.questionType||'single','single');
 assert(q.translationId?.prompt&&q.translationId.choices.length===q.choices.length);
 assert(q.explanation.length>60);
 assert(quiz.passages[0].text.includes(q.evidence),`Exact evidence missing: ${q.id}`);
 assert(isAnswered(q,q.answer)&&isCorrect(q,q.answer));
}
const positions=[0,0,0,0];for(const q of quiz.questions)positions[q.answer]++;assert.deepEqual(positions,[2,2,2,1]);
const key=quiz.questions.map(q=>q.answer);
assert.deepEqual(score(quiz.questions,key),{correct:7,incorrect:0,unanswered:0,total:7,percentage:100});
assert(!quiz.passages[0].text.includes('snack box'),'Transfer passage must use a different practical situation from the model');
assert.match(quiz.passages[0].text,/not a personal fitness or medical plan/,'The transfer text must state its limits as a general school activity');
console.log(`PASS Grade 10 Healthy Procedure: ${words}-word four-paragraph bilingual model, eight guided moves, three purposeful checks, modality/condition/safety scaffolding, and seven evidence-verified transfer questions.`);
